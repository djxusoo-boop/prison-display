import Foundation
let suite = "PrisonDisplayTests." + UUID().uuidString
let defaults = UserDefaults(suiteName: suite)!
defer { defaults.removePersistentDomain(forName: suite) }
var p = DisplayPreferences(defaults: defaults)
precondition(p.mode == 0 && p.resolution == 0 && p.fps == 0 && p.quality == 0)
let compatible = DisplayPreferences(defaults: defaults, compatibilityDefaults: true)
precondition(compatible.resolution == 1 && compatible.fps == 1)
print("PASS: new High Sierra setup starts at 720p30 without changing other platforms")
p.cursor = 1; p.mode = 1; p.resolution = 2; p.fps = 1; p.quality = 2; p.save(defaults: defaults)
precondition(DisplayPreferences(defaults: UserDefaults(suiteName: suite)!) == p)
precondition(DisplayPreferences(defaults: defaults, compatibilityDefaults: true) == p)
print("PASS: compatible defaults preserve every previously saved setting")
defaults.set(3, forKey: "PrisonDisplay.settings.cursor")
defaults.set(-1, forKey: "PrisonDisplay.settings.mode")
defaults.set(99, forKey: "PrisonDisplay.settings.resolution")
let recovered = DisplayPreferences(defaults: defaults)
precondition(recovered.cursor == 0 && recovered.mode == 0 && recovered.resolution == 0 && recovered.fps == 1)
for selected in VideoQualityProfile.all.indices {
    var choice = DisplayPreferences(defaults: defaults); choice.quality = selected; choice.save(defaults: defaults)
    precondition(DisplayPreferences(defaults: defaults).quality == selected)
}
precondition(VideoQualityProfile.all.map { $0.ceiling } == [12_000_000,6_000_000,20_000_000,40_000_000])
print("PASS: all quality ceilings persist; earlier indexes retain their meaning")
print("PASS: preferences persist and invalid saved indexes recover safely")
precondition(DisplayResolutionProfile.all.map { ($0.width, $0.height) }.elementsEqual([(1920,1080),(1280,720),(2560,1440)], by: ==))
var localVirtual = LocalVirtualDisplayPreferences(defaults: defaults)
precondition(localVirtual.resolution == DisplayResolutionProfile.local.count - 1)
localVirtual.resolution = 1; localVirtual.save(defaults: defaults)
precondition(LocalVirtualDisplayPreferences(defaults: defaults).resolution == 1)
print("PASS: remote indexes retain their meaning; local 4K HDMI choice persists")
var input = ReceiverPreferences(defaults: defaults)
precondition(!input.keyboard && !input.crossing)
input.keyboard = true; input.crossing = true; input.edge = 3; input.save(defaults: defaults)
precondition(ReceiverPreferences(defaults: UserDefaults(suiteName: suite)!) == input)
print("PASS: input choices and crossing edge survive app relaunch")
defaults.set(999, forKey: "desktopEdge")
precondition(ReceiverPreferences(defaults: defaults).edge == 0)
print("PASS: corrupt crossing edge recovers to a valid choice")

var secondary = DisplayPreferences(defaults: defaults, screenSlot: 1)
secondary.resolution = 1; secondary.fps = 1; secondary.quality = 2
let firstBefore = DisplayPreferences(defaults: defaults)
secondary.save(defaults: defaults, screenSlot: 1)
precondition(DisplayPreferences(defaults: defaults) == firstBefore)
precondition(DisplayPreferences(defaults: defaults, screenSlot: 1) == secondary)
print("PASS: each simultaneous screen retains its own settings")
var legacyQueries = 0
precondition(ScreenCaptureAccess.permitted(systemMajor: 10, query: { legacyQueries += 1; return false }))
precondition(legacyQueries == 0)
precondition(ScreenCaptureAccess.permitted(systemMajor: 10, query: nil))
precondition(!ScreenCaptureAccess.permitted(systemMajor: 11, query: nil))
precondition(!ScreenCaptureAccess.permitted(systemMajor: 11, query: { false }))
precondition(ScreenCaptureAccess.permitted(systemMajor: 11, query: { true }))
print("PASS: Catalina never calls unavailable permission API; modern capture fails closed")

precondition(ReconnectPreference.enabled(account: "sender", defaults: defaults))
ReconnectPreference.save(false, account: "sender", defaults: defaults)
precondition(!ReconnectPreference.enabled(account: "sender", defaults: UserDefaults(suiteName: suite)!))
precondition(ReconnectPreference.enabled(account: "sender.screen2", defaults: defaults))
precondition(ReconnectPreference.enabled(account: "receiver", defaults: defaults))
ReconnectPreference.save(true, account: "sender", defaults: defaults)
precondition(ReconnectPreference.enabled(account: "sender", defaults: defaults))
print("PASS: automatic reconnect defaults on, persists opt-out, and isolates each screen and role")

precondition(ReceiverPreferences(defaults: defaults).mouse)
input.mouse = false; input.keyboard = true; input.save(defaults: defaults)
let mouseOff = ReceiverPreferences(defaults: defaults)
precondition(!mouseOff.mouse && mouseOff.keyboard)
input.mouse = true; input.keyboard = false; input.save(defaults: defaults)
precondition(ReceiverPreferences(defaults: defaults).mouse && !ReceiverPreferences(defaults: defaults).keyboard)
var sending = SenderInputPreferences(defaults: defaults)
precondition(sending.mouse && sending.keyboard)
sending.mouse = false; sending.save(defaults: defaults)
precondition(!SenderInputPreferences(defaults: defaults).mouse && SenderInputPreferences(defaults: defaults).keyboard)
precondition(SenderInputPreferences(defaults: defaults, screenSlot: 1).mouse)
print("PASS: mouse and keyboard persist independently for receiving and each sending screen")
