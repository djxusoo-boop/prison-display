#!/usr/bin/env python3
"""Generate two hosted panels from the same tested controller implementation.

Only SENDER conditions are evaluated. Unknown conditions are retained, so
diagnostic/availability flags still have their normal Swift behavior.
"""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
source = (root / 'Sources/UI.swift').read_text()
start = source.index('final class AppController:')
controller = source[start:].removesuffix('\n#endif // !UNIFIED\n')
for role, sender in [('Send', True), ('Receive', False)]:
    active = True
    stack = []
    result = []
    for line in controller.splitlines():
        directive = line.strip()
        if directive.startswith('#if '):
            known = directive in ('#if SENDER', '#if !SENDER')
            condition = (sender if directive == '#if SENDER' else not sender) if known else True
            stack.append((active, condition, known))
            if not known and active:
                result.append(line)
            active = active and condition
        elif directive == '#else' and stack:
            parent, condition, known = stack[-1]
            if known:
                active = parent and not condition
            elif active:
                result.append(line)
        elif directive == '#endif' and stack:
            parent, _, known = stack.pop()
            if not known and parent:
                result.append(line)
            active = parent
        elif active:
            result.append(line.replace('final class AppController:', f'final class {role}PanelController:'))
    assert not stack
    target = root / f'build/{role}Panel.swift'
    generated = '// Generated by Packaging/generate-role-panels.py; edit Sources/UI.swift.\n#if UNIFIED\nimport AppKit\n\n#if !LEGACY\nimport Network\n#endif\nimport AVFoundation\nimport os.log\n' + '\n'.join(result) + '\n#endif\n'
    if not target.exists() or target.read_text() != generated:
        target.write_text(generated)
